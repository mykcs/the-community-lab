/**
 * Read-only, source-version-pinned proof of the option-button → raw-value path
 * in the observed public client. No official Korean prose/bundle is committed.
 * This is NOT a score formula, a live-DOM adapter, legal clearance or proof
 * that every user session follows the same navigation path.
 */
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { KOREAN_SOURCE_SNAPSHOT, verifyLiveKoreanClientSnapshot } from './verify-korean-source-snapshot.mjs';

const PINNED = Object.freeze({
  sha256: KOREAN_SOURCE_SNAPSHOT.sourceAssetSha256,
  bytes: 331_501,
});
const ASSET = 'https://thecommunity.co.kr/assets/index-C735ffg4.js';

export function verifyPinnedClientOptionBindings(bytes, expected = PINNED) {
  if (!Buffer.isBuffer(bytes) && !(bytes instanceof Uint8Array)) {
    throw new TypeError('客户端绑定审计只接受原始 JS 字节');
  }
  const actual = createHash('sha256').update(bytes).digest('hex');
  if (bytes.length !== expected.bytes || actual !== expected.sha256) {
    throw new Error('客户端 JS 指纹不匹配；不能推广旧版选项绑定证据');
  }
  const code = Buffer.from(bytes).toString('utf8');
  // Scoped to the observed quiz component, not an unrelated occurrence in the bundle.
  const start = code.indexOf('function Xm({season:l})');
  if (start === -1 || code.indexOf('function Xm({season:l})', start + 1) !== -1) {
    throw new Error('无法唯一定位已固定版本的官方答题组件');
  }
  const quiz = code.slice(start, start + 8500);
  const handle = quiz.indexOf('const Re=async ue=>{');
  const optionStart = quiz.indexOf('ze=l==="season-2"?[{value:"O",');
  const optionEnd = quiz.indexOf(']:k.allowedAnswers.map((ue,se)=>({value:ue,', optionStart);
  if (handle < 0 || optionStart <= handle || optionEnd <= optionStart ||
      optionEnd - optionStart > 1200 ||
      !quiz.includes('k=f[g]')) {
    throw new Error('答题处理器或源选项列表结构不符合已观察客户端');
  }
  const season2Values = [...quiz.slice(optionStart, optionEnd).matchAll(/\bvalue:"([OX])"/g)]
    .map(match => match[1]);
  if (JSON.stringify(season2Values) !== '["O","X"]') {
    throw new Error('第二季按钮的原始 O/X 值与顺序无法确认');
  }
  const answerHandler = quiz.slice(handle, optionStart);
  if (!answerHandler.includes('const se={...A,[k.id]:ue}') ||
      !answerHandler.includes('g<f.length-1') ||
      !answerHandler.includes('D(g+1)') ||
      !answerHandler.includes('ni.submit({season:l,answers:se,')) {
    throw new Error('选项值→源题 ID→提交答案的原始值链路不完整');
  }
  const buttons = quiz.indexOf('ze.map((ue,se)=>d.jsx("button",{', optionEnd);
  if (buttons < 0 || buttons - optionEnd > 3800 ||
      !quiz.slice(buttons, buttons + 450).includes('onClick:()=>Re(ue.value)')) {
    throw new Error('按钮点击未证明传递原始选项值而非展示位置');
  }
  // Matching answers and version strings are not the entire request identity.
  // The pinned client restores per-season browser-local answers and can send
  // optional submission metadata. This is only client-source evidence; it
  // does NOT prove those fields influence any official score discrepancy.
  const observedNavigation = [
    '[A,H]=j.useState(()=>JSON.parse(localStorage.getItem(c)??"{}"))',
    'j.useEffect(()=>localStorage.setItem(c,JSON.stringify(A)),[A,c])',
    'se.key==="ArrowLeft"&&g>0&&D(g-1)',
    'onClick:()=>{fe(null),ge(null),D(Math.max(0,g-1))}',
  ];
  const observedRequest = [
    '...S.trim()?{displayName:S.trim()}:{}',
    '...s.get("ref")?{referredBy:s.get("ref")}:{}',
    '...s.get("utm_source")?{campaignSource:s.get("utm_source")}:{}',
    'consentVersion:"result-storage-v1"',
    '},crypto.randomUUID())',
  ];
  if (!observedNavigation.every(fragment => quiz.includes(fragment)) ||
      !observedRequest.every(fragment => answerHandler.includes(fragment))) {
    throw new Error('客户端返回导航、本机答卷状态或提交上下文证据不完整');
  }
  // No claim about scoring: the client sends a map of source IDs to source
  // values; the score is generated by the unknown server-side implementation.
  return Object.freeze({
    status: 'PINNED_CLIENT_OPTION_BINDING_OBSERVED',
    sourceAssetSha256: actual,
    season2OptionValues: Object.freeze(season2Values),
    season1OptionsFromQuestionAllowedAnswers: true,
    buttonSendsSourceValueNotDisplayPosition: true,
    answerMapUsesSourceQuestionId: true,
    sameRawAnswerMapSentAtFinalSubmission: true,
    browserRestoresPerSeasonAnswersFromLocalStorage: true,
    browserWritesPerSeasonAnswersToLocalStorage: true,
    keyboardAndButtonBackNavigationObserved: true,
    submissionMayIncludeDisplayNameReferralAndCampaign: true,
    submissionIncludesConsentVersion: true,
    submissionUsesFreshRequestId: true,
    theseSubmissionFieldsAffectScore: 'UNKNOWN',
    scoringAlgorithmKnown: false,
    realDomSourceIdExposed: false,
  });
}

export async function verifyCurrentPublicClientBindings(request = globalThis.fetch) {
  // The existing conservative gate first proves both public test routes still
  // reference the pinned asset; no sessions, clicks, answers or POST requests.
  await verifyLiveKoreanClientSnapshot(request);
  const response = await request(ASSET, {
    method: 'GET',
    headers: { Accept: 'application/javascript' },
    signal: AbortSignal.timeout(15_000),
  });
  if (!response.ok || response.url !== ASSET ||
      !/javascript/i.test(response.headers.get('content-type') || '')) {
    throw new Error('固定官方 JS 未能按只读 GET 方式获取');
  }
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length > 500_000) throw new Error('客户端资源体积异常');
  return verifyPinnedClientOptionBindings(bytes);
}

// Explicit opt-in only: never run a live external-site request in tests/build.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.length !== 3 || process.argv[2] !== '--live-readonly') {
    console.error('Usage: node scripts/verify-client-option-bindings.mjs --live-readonly');
    process.exitCode = 2;
  } else {
    verifyCurrentPublicClientBindings()
      .then(result => console.log(JSON.stringify(result, null, 2)))
      .catch(() => {
        // Do not echo responses or original Korean contents on failure.
        console.error('固定客户端选项绑定审计失败：请检查当前官方资源及版本');
        process.exitCode = 1;
      });
  }
}
